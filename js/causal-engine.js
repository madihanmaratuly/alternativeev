  generate(query) {
    const clean = query.toLowerCase().trim();

    // 1. Проверяем точные пресеты из presets.js
    if (typeof findMatchingPreset === "function") {
      const preset = findMatchingPreset(query);
      if (preset) {
        return this.enrichScenario(preset);
      }
    }

    // 2. Проверяем расширенную базу знаний
    for (const [key, data] of Object.entries(this.knowledgeBase)) {
      for (const m of data.matches) {
        if (clean.includes(m)) {
          return this.enrichScenario({ ...data, query: query, id: "kb-" + key });
        }
      }
    }

    // 3. Умный расширенный синтезатор для любого вопроса
    return this.synthesizeCustomScenario(query);
  }

