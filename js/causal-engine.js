  detectEpochYear(clean) {
    const yearMatch = clean.match(/\b(1[0-9]{3}|20[0-2][0-9])\b/);
    if (yearMatch) return parseInt(yearMatch[1], 10);
    if (clean.includes("рим") || clean.includes("цезар") || clean.includes("антич")) return 476;
    if (clean.includes("средневек") || clean.includes("рыцар")) return 1350;
    if (clean.includes("1812") || clean.includes("наполеон")) return 1815;
    if (clean.includes("1917") || clean.includes("революц")) return 1917;
    if (clean.includes("1945") || clean.includes("вторая миров")) return 1945;
    if (clean.includes("1961") || clean.includes("гагарин") || clean.includes("космос")) return 1961;
    if (clean.includes("1991") || clean.includes("ссср")) return 1991;
    return 1975;
  }
